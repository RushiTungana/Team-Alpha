package com.task_1.java.copy;


public class LOOPS {

	public static void main(String[] args) {
		System.out.println("FOR LOOP");
		for (int i = 1; i <= 10 ; i++) {
			System.out.println(i);
		}
		System.out.println("==================");
		System.out.println("WHILE");
		int i = 2;
		while (i<=20) {
			System.out.println(i);
			i++;
		}
		System.out.println("=============");
		System.out.println("DO WHILE");
		int j = 10;
		do {
			System.out.println(j);
			j--;
		}while(j>=1);
		
	}
}


